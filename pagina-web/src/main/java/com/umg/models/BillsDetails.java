package com.umg.models;

public class BillsDetails {

    private long id;
    private int num;
    private int idRegisters;

    public long getId() {
        return id;
    }

    public void setId(long id) {
        this.id = id;
    }

    public int getNum() {
        return num;
    }

    public void setNum(int num) {
        this.num = num;
    }

    public int getIdRegisters() {
        return idRegisters;
    }

    public void setIdRegisters(int idRegisters) {
        this.idRegisters = idRegisters;
    }

}
